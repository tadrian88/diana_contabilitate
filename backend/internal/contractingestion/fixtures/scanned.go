import "strings"

// Tiny bitmap font keeps the scanned fixture reproducible and dependency-free.
// The resulting PDF contains actual readable contract text only as raster pixels.
func scannedContract() (int, int, []byte) {
	const width, height, scale = 1100, 400, 3
	pixels := make([]byte, width*height)
	for i := range pixels {
		pixels[i] = 255
	}
	lines := []string{"SERVICE CONTRACT CTR-2026-01", "SUPPLIER FURNIZOR EXTRAS SRL", "SUPPLIER CUI RO12345678", "BUYER CUI RO10000000", "EFFECTIVE 2026-01-01 TO 2027-12-31", "VALUE 125000.00 RON", "UNIT SERVICII", "PAYMENT TERMS 30 ZILE"}
	for row, line := range lines {
		for col, char := range line {
			glyph := strings.Split(bitmapGlyphs[char], "/")
			for y, bits := range glyph {
				for x, bit := range bits {
					if bit != '1' {
						continue
					}
					for dy := 0; dy < scale; dy++ {
						for dx := 0; dx < scale; dx++ {
							px, py := 20+col*6*scale+x*scale+dx, 20+row*40+y*scale+dy
							if px < width && py < height {
								pixels[py*width+px] = 0
							}
						}
					}
				}
			}
		}
	}
	return width, height, pixels
}

